package link_test

import (
	"fmt"

	"github.com/modern-engineering/prototype/ir"
	"github.com/modern-engineering/prototype/ir/link"
)

// Generated selectors make Go's compiler responsible for resolving exports.
// Their concrete types impose no common capability on the resulting values.
func ExampleSource() {
	model := ir.Model{Nodes: []ir.Node{
		{Name: "input", Definition: ir.Symbol{Package: "os", Name: "Stdin"}},
		{Name: "null", Definition: ir.Symbol{Package: "os", Name: "DevNull"}},
	}}
	source, err := link.Source("inspection", "Definitions", model)
	if err != nil {
		fmt.Println(err)
		return
	}
	fmt.Print(string(source))

	// Output:
	// // Code generated by ir/link. DO NOT EDIT.
	//
	// package inspection
	//
	// import (
	// 	catalogue0 "github.com/modern-engineering/prototype/ir"
	// 	catalogue1 "os"
	// )
	//
	// func Definitions() map[catalogue0.Symbol]any {
	// 	return map[catalogue0.Symbol]any{
	// 		{Package: "os", Name: "DevNull"}: catalogue1.DevNull,
	// 		{Package: "os", Name: "Stdin"}:   catalogue1.Stdin,
	// 	}
	// }
}
