// Package link generates Go code connecting structural symbols to compiled
// catalogue values. The resulting side table leaves the structural model intact.
// Consumers discover capabilities using ordinary Go type assertions.
//
// Generation is not module resolution or execution. The caller compiles the
// source in a Go build whose module requirements select the referenced code.
// Missing packages, missing exports, and exports that are not values fail that
// build. An unfamiliar concrete type can link successfully without exposing I/O.
// Importing catalogue packages runs their initializers when the binary starts;
// linkage does not invoke descriptor constructors or runners.
package link

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"slices"
	"strconv"
	"strings"

	"github.com/modern-engineering/prototype/ir"
)

// ErrIdentifier means a name cannot be used in the generated declaration,
// or a referenced symbol is not exported.
var ErrIdentifier = errors.New("unusable Go identifier")

// Source generates a Go file in packageName containing functionName. The
// generated function returns a fresh map[ir.Symbol]any of the definitions used
// by model.Nodes. Repeated occurrences of a definition share one table entry.
// Calling the function reads the exported values; it does not instantiate them.
//
// The source is deterministic for a set of definitions. Module requirements,
// bindings, and occurrence names remain structural data and are not interpreted
// here. Symbol existence and whether a symbol denotes a value are checked by
// the Go compiler, not by source generation.
func Source(packageName, functionName string, model ir.Model) ([]byte, error) {
	for _, name := range []string{packageName, functionName} {
		if !token.IsIdentifier(name) || name == "_" {
			return nil, fmt.Errorf("%w: %q", ErrIdentifier, name)
		}
	}

	if functionName == "any" || functionName == "init" || packageName == "main" && functionName == "main" {
		return nil, fmt.Errorf("%w: %q", ErrIdentifier, functionName)
	}

	const irPath = "github.com/modern-engineering/prototype/ir"
	packages := map[string]string{irPath: ""}
	definitions := make(map[ir.Symbol]bool)
	for _, node := range model.Nodes {
		symbol := node.Definition
		if !token.IsIdentifier(symbol.Name) || !ast.IsExported(symbol.Name) {
			return nil, fmt.Errorf("%w: %q", ErrIdentifier, symbol.Name)
		}
		packages[symbol.Package] = ""
		definitions[symbol] = true
	}
	paths := make([]string, 0, len(packages))
	for path := range packages {
		paths = append(paths, path)
	}
	slices.Sort(paths)
	symbols := make([]ir.Symbol, 0, len(definitions))
	for symbol := range definitions {
		symbols = append(symbols, symbol)
	}
	slices.SortFunc(symbols, func(a, b ir.Symbol) int {
		if a.Package != b.Package {
			return strings.Compare(a.Package, b.Package)
		}
		return strings.Compare(a.Name, b.Name)
	})

	var source bytes.Buffer
	fmt.Fprintf(&source, "// Code generated by ir/link. DO NOT EDIT.\n\npackage %s\n\nimport (\n", packageName)
	for i, path := range paths {
		alias := fmt.Sprintf("catalogue%d", i)
		if alias == functionName {
			alias += "_"
		}
		packages[path] = alias
		fmt.Fprintf(&source, "%s %s\n", alias, strconv.Quote(path))
	}
	fmt.Fprintf(&source, ")\n\nfunc %s() map[%s.Symbol]any {\nreturn map[%s.Symbol]any{\n", functionName, packages[irPath], packages[irPath])
	for _, symbol := range symbols {
		fmt.Fprintf(&source, "{Package: %q, Name: %q}: %s.%s,\n", symbol.Package, symbol.Name, packages[symbol.Package], symbol.Name)
	}
	source.WriteString("}\n}\n")
	return format.Source(source.Bytes())
}
