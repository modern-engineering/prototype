// golden is the exact expected output of [TestSource]'s fixture, with ~
// standing in for backquotes (the generated code contains raw string
// literals, so the golden itself cannot be one). The fixture exercises
// the alias collision rule (two packages named ff), all three citizen
// kinds (provision-type and symbol-type citizens register through
// solution.Provision and solution.Symbol), an empty registration (no
// import, no Elements), and both unit quoting forms: a.sdl survives a
// raw literal, b.sdl contains a backquote and falls back to an
// interpreted literal.
const golden = `// Code generated by sdl build; DO NOT EDIT.

package main

import (
	"os"

	"github.com/modern-engineering/prototype/solution"

	ff "example.com/alpha/ff"
	ff2 "example.com/beta/ff"
)

func main() {
	os.Exit(solution.MainCompile(solution.CompileConfig{
		Solution: "demo",
		Dir:      "/work/demo",
		Units: []solution.Unit{
			{Name: "a.sdl", Source: ~solution demo

deploy ff.Ping as P
~},
			{Name: "b.sdl", Source: "solution demo\n// tick ~raw~\n"},
		},
		Catalogue: []solution.Package{
			{
				Path: "example.com/alpha/ff",
				Name: "ff",
				Elements: []solution.Element{
					solution.App("Ping", ff.Ping),
					solution.App("Pong", ff.Pong),
				},
			},
			{
				Path: "example.com/beta/ff",
				Name: "ff",
				Elements: []solution.Element{
					solution.Provision("Bus", ff2.Bus),
					solution.App("Echo", ff2.Echo),
					solution.Symbol("Token", ff2.Token),
				},
			},
			{
				Path: "example.com/empty",
				Name: "empty",
			},
		},
		Generation: 7,
	}))
}
`

func TestSource(t *testing.T) {
	sol := &load.Solution{
		Name: "demo",
		Dir:  "/work/demo",
		Units: []load.Unit{
			{Name: "a.sdl", Source: "solution demo\n\ndeploy ff.Ping as P\n"},
			{Name: "b.sdl", Source: "solution demo\n// tick `raw`\n"},
		},
	}
	pkgs := []Package{
		{Path: "example.com/alpha/ff", Name: "ff", Citizens: []Citizen{
			{Name: "Ping", Kind: KindComponent},
			{Name: "Pong", Kind: KindComponent},
		}},
		{Path: "example.com/beta/ff", Name: "ff", Citizens: []Citizen{
			{Name: "Bus", Kind: KindProvision},
			{Name: "Echo", Kind: KindComponent},
			{Name: "Token", Kind: KindSymbol},
		}},
		{Path: "example.com/empty", Name: "empty"},
	}

	got := Source(sol, pkgs, 7)
	want := strings.ReplaceAll(golden, "~", "`")
	if string(got) != want {
		t.Errorf("Source mismatch\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}

	// The emitted body claims to be canonical gofmt output; hold it to
	// that (the golden then guards the claim against emitter drift).
	formatted, err := format.Source(got)
	if err != nil {
		t.Fatalf("generated source does not parse: %v", err)
	}
	if !bytes.Equal(formatted, got) {
		t.Errorf("generated source is not gofmt-canonical\n--- gofmt ---\n%s", formatted)
	}
}

// stubBuildInfo swaps the build-info read for one crafted shape and
// restores it when the test ends.
func stubBuildInfo(t *testing.T, info *debug.BuildInfo, ok bool) {
	t.Helper()
	restore := readBuildInfo
	readBuildInfo = func() (*debug.BuildInfo, bool) { return info, ok }
	t.Cleanup(func() { readBuildInfo = restore })
}

// TestSourceTool pins the Tool emission: an installed CLI's ordinary
// version lands in the generated CompileConfig (the emitted body still
// gofmt-canonical), while every locally sourced shape — a VCS-stamped
// checkout build, a (devel) build, a foreign main module, no build
// info at all — emits no Tool line, exactly the bytes TestSource's
// golden pins under the test binary's own build info.
func TestSourceTool(t *testing.T) {
	sol := &load.Solution{
		Name:  "demo",
		Dir:   "/work/demo",
		Units: []load.Unit{{Name: "a.sdl", Source: "solution demo\n"}},
	}

	stubBuildInfo(t, &debug.BuildInfo{Main: debug.Module{Path: prototypePath, Version: "v0.3.1"}}, true)
	got := Source(sol, nil, 7)
	if !strings.Contains(string(got), "\t\tGeneration: 7,\n\t\tTool:       \"v0.3.1\",\n") {
		t.Errorf("Source did not emit the Tool field after Generation:\n%s", got)
	}
	formatted, err := format.Source(got)
	if err != nil {
		t.Fatalf("generated source does not parse: %v", err)
	}
	if !bytes.Equal(formatted, got) {
		t.Errorf("generated source is not gofmt-canonical\n--- gofmt ---\n%s", formatted)
	}

	silent := map[string]struct {
		info *debug.BuildInfo
		ok   bool
	}{
		"vcs-stamped checkout build": {&debug.BuildInfo{
			Main:     debug.Module{Path: prototypePath, Version: "v0.0.0-20260101000000-0123456789ab+dirty"},
			Settings: []debug.BuildSetting{{Key: "vcs.revision", Value: "0123456789ab"}},
		}, true},
		"devel build":         {&debug.BuildInfo{Main: debug.Module{Path: prototypePath, Version: "(devel)"}}, true},
		"foreign main module": {&debug.BuildInfo{Main: debug.Module{Path: "example.test/tool", Version: "v1.0.0"}}, true},
		"no build info":       {nil, false},
	}
	for name, tt := range silent {
		t.Run(name, func(t *testing.T) {
			stubBuildInfo(t, tt.info, tt.ok)
			if got := Source(sol, nil, 7); strings.Contains(string(got), "Tool:") {
				t.Errorf("Source emitted a Tool line:\n%s", got)
			}
		})
	}
}

func TestQuoteSource(t *testing.T) {
	tests := []struct {
		in, want string
	}{
		{"plain\ntext\n", "`plain\ntext\n`"},
		{"has `tick`\n", `"has ` + "`tick`" + `\n"`},
		{"windows\r\nline\n", `"windows\r\nline\n"`},
	}
	for _, tt := range tests {
		if got := quoteSource(tt.in); got != tt.want {
			t.Errorf("quoteSource(%q) = %s, want %s", tt.in, got, tt.want)
		}
	}
}
