// HostSource emits the generated tailored host for one solution:
// Source's sibling for sdl run, embedding the same unit sources and
// catalogue registrations but handing them — together with the child's
// own command line — to host.MainTailored instead of the compiler
// entry point. Where the compiler main emits the image and exits, the
// tailored host compiles the embedded units in memory and enacts the
// resulting image in-process (Mode T, the go test mechanics: a program
// built per invocation around the material under the verb).
//
// The run loop always enacts a fresh generation 1: the image lives and
// dies inside the process, so there is no earlier generation to count
// from. Tool is embedded on the same terms as Source's.
func HostSource(sol *load.Solution, pkgs []Package) []byte {
	aliases := packageAliases(pkgs, "os", "solution", "host")

	var b bytes.Buffer
	b.WriteString("// Code generated by sdl run; DO NOT EDIT.\n")
	b.WriteString("\npackage main\n")
	b.WriteString("\nimport (\n")
	b.WriteString("\t\"os\"\n")
	b.WriteString("\n\t\"github.com/modern-engineering/prototype/solution\"\n")
	b.WriteString("\t\"github.com/modern-engineering/prototype/solution/host\"\n")
	writeCatalogueImports(&b, pkgs, aliases)
	b.WriteString(")\n")

	b.WriteString("\nfunc main() {\n")
	b.WriteString("\tos.Exit(host.MainTailored(solution.CompileConfig{\n")
	writeCompileConfig(&b, sol, pkgs, aliases, 1)
	b.WriteString("\t}, os.Args[1:]))\n}\n")
	return b.Bytes()
}
