// Source emits the generated compiler for one solution: a package main
// that embeds the unit sources verbatim (generation and execution can
// never skew), registers the discovered catalogue, and hands both to
// solution.MainCompile. The body is written to already be canonical
// gofmt output, the testmain precedent; no formatting pass runs over it.
//
// The emitted CompileConfig leaves Output and Stderr nil: the compiler
// writes the image to its stdout and diagnostics to its stderr, and the
// build driver owns both streams.
func Source(sol *load.Solution, pkgs []Package, generation int64) []byte {
	aliases := packageAliases(pkgs)

	var b bytes.Buffer
	b.WriteString("// Code generated by sdl build; DO NOT EDIT.\n")
	b.WriteString("\npackage main\n")
	b.WriteString("\nimport (\n")
	b.WriteString("\t\"os\"\n")
	b.WriteString("\n\t\"github.com/modern-engineering/prototype/solution\"\n")
	imported := false
	for _, p := range pkgs {
		if len(p.Citizens) == 0 {
			continue // registered empty; nothing references it
		}
		if !imported {
			b.WriteString("\n")
			imported = true
		}
		fmt.Fprintf(&b, "\t%s %q\n", aliases[p.Path], p.Path)
	}
	b.WriteString(")\n")

	b.WriteString("\nfunc main() {\n")
	b.WriteString("\tos.Exit(solution.MainCompile(solution.CompileConfig{\n")
	// The scalar run aligns Dir's value with Solution's, exactly as
	// gofmt would.
	fmt.Fprintf(&b, "\t\tSolution: %s,\n", strconv.Quote(sol.Name))
	fmt.Fprintf(&b, "\t\tDir:      %s,\n", strconv.Quote(sol.Dir))
	b.WriteString("\t\tUnits: []solution.Unit{\n")
	for _, u := range sol.Units {
		fmt.Fprintf(&b, "\t\t\t{Name: %s, Source: %s},\n", strconv.Quote(u.Name), quoteSource(u.Source))
	}
	b.WriteString("\t\t},\n")
	if len(pkgs) > 0 {
		b.WriteString("\t\tCatalogue: []solution.Package{\n")
		for _, p := range pkgs {
			b.WriteString("\t\t\t{\n")
			fmt.Fprintf(&b, "\t\t\t\tPath: %s,\n", strconv.Quote(p.Path))
			fmt.Fprintf(&b, "\t\t\t\tName: %s,\n", strconv.Quote(p.Name))
			if len(p.Citizens) > 0 {
				b.WriteString("\t\t\t\tElements: []solution.Element{\n")
				for _, c := range p.Citizens {
					fmt.Fprintf(&b, "\t\t\t\t\tsolution.App(%s, %s.%s),\n", strconv.Quote(c), aliases[p.Path], c)
				}
				b.WriteString("\t\t\t\t},\n")
			}
			b.WriteString("\t\t\t},\n")
		}
		b.WriteString("\t\t},\n")
	}
	fmt.Fprintf(&b, "\t\tGeneration: %d,\n", generation)
	b.WriteString("\t}))\n}\n")
	return b.Bytes()
}

// packageAliases assigns each imported package a stable, unique local
// alias derived from its Go package name: the name itself, or on
// collision the name with 2, 3, ... appended. The generated file's own
// imports are reserved. Aliases are always written out, so the emitted
// source never depends on a path's last element matching the package
// name. Determinism comes from the input order: pkgs arrives sorted by
// path.
func packageAliases(pkgs []Package) map[string]string {
	used := map[string]bool{"os": true, "solution": true}
	aliases := make(map[string]string, len(pkgs))
	for _, p := range pkgs {
		if len(p.Citizens) == 0 {
			continue // not imported, needs no alias
		}
		alias := p.Name
		for n := 2; used[alias]; n++ {
			alias = p.Name + strconv.Itoa(n)
		}
		used[alias] = true
		aliases[p.Path] = alias
	}
	return aliases
}

// quoteSource renders a unit's source text as a Go string literal: a raw
// (backquoted) literal when the text survives one — no backquotes, and
// no carriage returns, which raw literals silently drop — otherwise an
// interpreted literal via strconv.Quote.
func quoteSource(s string) string {
	if strings.ContainsAny(s, "`\r") {
		return strconv.Quote(s)
	}
	return "`" + s + "`"
}
