// hostGolden is the exact expected output of [TestHostSource]'s
// fixture, ~ standing in for backquotes as in [golden]. Beside the
// shared emission (already pinned by TestSource), the fixture pins the
// host frame: the sdl run header, the solution/host import, the
// MainTailored call threading os.Args through, the always-1
// generation, and the "host" alias reservation — a catalogue package
// named host must yield to the framework import.
const hostGolden = `// Code generated by sdl run; DO NOT EDIT.

package main

import (
	"os"

	"github.com/modern-engineering/prototype/solution"
	"github.com/modern-engineering/prototype/solution/host"

	ff "example.com/alpha/ff"
	host2 "example.com/host"
)

func main() {
	os.Exit(host.MainTailored(solution.CompileConfig{
		Solution: "demo",
		Dir:      "/work/demo",
		Units: []solution.Unit{
			{Name: "a.sdl", Source: ~solution demo

deploy ff.Ping as P
~},
		},
		Catalogue: []solution.Package{
			{
				Path: "example.com/alpha/ff",
				Name: "ff",
				Elements: []solution.Element{
					solution.App("Ping", ff.Ping),
				},
			},
			{
				Path: "example.com/host",
				Name: "host",
				Elements: []solution.Element{
					solution.Provision("Bus", host2.Bus),
				},
			},
		},
		Generation: 1,
	}, os.Args[1:]))
}
`

func TestHostSource(t *testing.T) {
	sol := &load.Solution{
		Name: "demo",
		Dir:  "/work/demo",
		Units: []load.Unit{
			{Name: "a.sdl", Source: "solution demo\n\ndeploy ff.Ping as P\n"},
		},
	}
	pkgs := []Package{
		{Path: "example.com/alpha/ff", Name: "ff", Citizens: []Citizen{
			{Name: "Ping", Kind: KindComponent},
		}},
		{Path: "example.com/host", Name: "host", Citizens: []Citizen{
			{Name: "Bus", Kind: KindProvision},
		}},
	}

	got := HostSource(sol, pkgs)
	want := strings.ReplaceAll(hostGolden, "~", "`")
	if string(got) != want {
		t.Errorf("HostSource mismatch\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}

	// The emitted body claims to be canonical gofmt output; hold it to
	// that (the golden then guards the claim against emitter drift).
	formatted, err := format.Source(got)
	if err != nil {
		t.Fatalf("generated source does not parse: %v", err)
	}
	if !bytes.Equal(formatted, got) {
		t.Errorf("generated source is not gofmt-canonical\n--- gofmt ---\n%s", formatted)
	}
}
